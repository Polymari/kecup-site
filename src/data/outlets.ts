export const OUTLETS_BY_SLUG: Record<string, Outlet> = Object.fromEntries(
  OUTLETS.map((outlet) => [outlet.slug, outlet]),
)

export function getOutletBySlug(slug: string): Outlet {
  const outlet = OUTLETS_BY_SLUG[slug]
  if (!outlet) throw new Error(`Unknown outlet: ${slug}`)
  return outlet
}

